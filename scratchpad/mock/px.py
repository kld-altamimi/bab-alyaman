def _glyph(font, ch):
    if font is FONT_S or font is FONT_B:
        ch = ch.upper()
    return font.get(ch, font.get('?'))


def text_w(s, font=FONT_M, sp=1, scale_=1):
    w = 0
    for ch in s:
        g = _glyph(font, ch)
        w += (len(g[0]) + sp) * scale_
    return max(0, w - sp * scale_)


def font_h(font):
    return 9 if font is FONT_B else (7 if font is FONT_M else 5)


def text_img(s, font=FONT_M, color='#ffffff', sp=1, scale_=1):
    cap = font_h(font)
    w = text_w(s, font, sp, 1)
    im = new(max(1, w), cap + 2)
    px = im.load()
    c = rgba(color)
    x = 0
    for ch in s:
        g = _glyph(font, ch)
        for yy, row in enumerate(g):
            for xx, v in enumerate(row):
                if v == '#':
                    px[x + xx, yy] = c
        x += len(g[0]) + sp
    if scale_ > 1:
        im = scale(im, scale_)
    return im


def text(dst, x, y, s, font=FONT_M, color='#ffffff', shadow=None, edge=None,
         sp=1, scale_=1, align='l'):
    """Draw text; x,y is the top-left of the cap height. Returns width."""
    im = text_img(s, font, color, sp, scale_)
    w = text_w(s, font, sp, scale_)
    if align == 'c':
        x -= w // 2
    elif align == 'r':
        x -= w
    if edge:
        o = outline(im, edge, diag=True)
        blit(dst, o, x - 1, y - 1)
    elif shadow:
        sh = silhouette(im, shadow)
        blit(dst, sh, x + scale_, y + scale_)
        blit(dst, im, x, y)
    else:
        blit(dst, im, x, y)
    return w


def wrap(s, font, maxw, sp=1):
    words, lines, cur = s.split(' '), [], ''
    for wd in words:
        t = (cur + ' ' + wd).strip()
        if text_w(t, font, sp) <= maxw or not cur:
            cur = t
        else:
            lines.append(cur)
            cur = wd
    if cur:
        lines.append(cur)
    return lines


def rng(seed):
    return random.Random(seed)


def save(im, path, zoom=1):
    if zoom > 1:
        im = scale(im, zoom)
    im.save(path)
