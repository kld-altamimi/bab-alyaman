# px.py - a tiny pixel-art toolkit: palette, sprites from text grids, outlines,
# dithered gradients and two hand-made bitmap fonts.
from PIL import Image, ImageDraw
import random

W, H = 468, 216          # the game's widest logical screen (19.5:9 phones)


def hexc(h, a=255):
    h = h.lstrip('#')
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a)


def new(w=W, h=H, color=(0, 0, 0, 0)):
    return Image.new('RGBA', (w, h), color)


def rgba(c, a=None):
    if isinstance(c, str):
        c = hexc(c)
    if a is not None:
        c = (c[0], c[1], c[2], a)
    return c


# ---------------------------------------------------------------- blitting
def blit(dst, src, x, y, flip=False, opacity=1.0):
    x, y = int(round(x)), int(round(y))
    if flip:
        src = src.transpose(Image.FLIP_LEFT_RIGHT)
    if opacity < 1.0:
        a = src.getchannel('A').point(lambda v: int(v * opacity))
        src = src.copy()
        src.putalpha(a)
    sx0, sy0 = max(0, -x), max(0, -y)
    sx1, sy1 = min(src.width, dst.width - x), min(src.height, dst.height - y)
    if sx1 <= sx0 or sy1 <= sy0:
        return
    part = src.crop((sx0, sy0, sx1, sy1))
    dst.alpha_composite(part, (x + sx0, y + sy0))


def put(dst, x, y, c):
    if 0 <= x < dst.width and 0 <= y < dst.height:
        c = rgba(c)
        if c[3] == 255:
            dst.putpixel((x, y), c)
        else:
            tmp = new(1, 1, c)
            dst.alpha_composite(tmp, (x, y))


def rect(dst, x0, y0, x1, y1, c):
    """Inclusive rectangle fill, alpha-aware."""
    c = rgba(c)
    x0, x1 = sorted((int(x0), int(x1)))
    y0, y1 = sorted((int(y0), int(y1)))
    x0, y0 = max(0, x0), max(0, y0)
    x1, y1 = min(dst.width - 1, x1), min(dst.height - 1, y1)
    if x1 < x0 or y1 < y0:
        return
    if c[3] == 255:
        dst.paste(c, (x0, y0, x1 + 1, y1 + 1))
    else:
        tmp = new(x1 - x0 + 1, y1 - y0 + 1, c)
        dst.alpha_composite(tmp, (x0, y0))


def hline(dst, x0, x1, y, c):
    rect(dst, x0, y, x1, y, c)


def vline(dst, x, y0, y1, c):
    rect(dst, x, y0, x, y1, c)


def line(dst, x0, y0, x1, y1, c, width=1):
    d = ImageDraw.Draw(dst)
    d.line((x0, y0, x1, y1), fill=rgba(c), width=width)


def poly(dst, pts, c, outline_c=None):
    d = ImageDraw.Draw(dst)
    d.polygon([(int(x), int(y)) for x, y in pts], fill=rgba(c),
              outline=rgba(outline_c) if outline_c else None)


def ellipse(dst, x0, y0, x1, y1, c, outline_c=None):
    d = ImageDraw.Draw(dst)
    d.ellipse((x0, y0, x1, y1), fill=rgba(c) if c else None,
              outline=rgba(outline_c) if outline_c else None)


def disc(dst, cx, cy, r, c):
    """Pixel-perfect filled circle, alpha-aware."""
    c = rgba(c)
    for yy in range(-r, r + 1):
        for xx in range(-r, r + 1):
            if xx * xx + yy * yy <= r * r + r * 0.8:
                put(dst, cx + xx, cy + yy, c)


def ring(dst, cx, cy, r, c, t=1):
    c = rgba(c)
    for yy in range(-r, r + 1):
        for xx in range(-r, r + 1):
            d2 = xx * xx + yy * yy
            if (r - t) * (r - t) + (r - t) * 0.8 < d2 <= r * r + r * 0.8:
                put(dst, cx + xx, cy + yy, c)


def rrect(dst, x0, y0, x1, y1, c, r=2):
    """Rounded rectangle (pixel corners)."""
    rect(dst, x0 + r, y0, x1 - r, y1, c)
    rect(dst, x0, y0 + r, x1, y1 - r, c)
    if r >= 2:
        rect(dst, x0 + 1, y0 + 1, x1 - 1, y1 - 1, c)


# ---------------------------------------------------------------- dithering
BAYER4 = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


def dither_rect(dst, x0, y0, x1, y1, c, level):
    """Paint colour c over the box on `level` of every 16 pixels (Bayer)."""
    c = rgba(c)
    px = dst.load()
    for y in range(max(0, y0), min(dst.height, y1 + 1)):
        for x in range(max(0, x0), min(dst.width, x1 + 1)):
            if BAYER4[y % 4][x % 4] < level:
                px[x, y] = c


def vbands(dst, x0, y0, x1, y1, colors, soft=3):
    """Vertical colour bands with a short dithered seam between them."""
    n = len(colors)
    hgt = y1 - y0 + 1
    px = dst.load()
    cols = [rgba(c) for c in colors]
    for y in range(y0, y1 + 1):
        t = (y - y0) / max(1, hgt) * n
        i = min(n - 1, int(t))
        f = t - i
        band_h = hgt / n
        dist_px = (1 - f) * band_h          # distance to the next seam
        lvl = 0
        if i < n - 1 and dist_px <= soft * 2:
            lvl = int(16 * (1 - dist_px / (soft * 2)) * 0.75)
        for x in range(x0, x1 + 1):
            if lvl and BAYER4[y % 4][x % 4] < lvl:
                px[x, y] = cols[i + 1]
            else:
                px[x, y] = cols[i]


# ---------------------------------------------------------------- sprites
def sprite(rows, pal):
    rows = [r for r in rows]
    h = len(rows)
    w = max(len(r) for r in rows)
    im = new(w, h)
    px = im.load()
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch in '. ':
                continue
            px[x, y] = rgba(pal[ch])
    return im


def outline(im, color, diag=False):
    """Return a copy 2px larger with a 1px outline around the silhouette."""
    color = rgba(color)
    w, h = im.size
    out = new(w + 2, h + 2)
    out.alpha_composite(im, (1, 1))
    src = out.copy().load()
    o = out.load()
    nb = [(1, 0), (-1, 0), (0, 1), (0, -1)]
    if diag:
        nb += [(1, 1), (-1, 1), (1, -1), (-1, -1)]
    for y in range(h + 2):
        for x in range(w + 2):
            if src[x, y][3] == 0:
                for dx, dy in nb:
                    xx, yy = x + dx, y + dy
                    if 0 <= xx < w + 2 and 0 <= yy < h + 2 and src[xx, yy][3] > 0:
                        o[x, y] = color
                        break
    return out


def scale(im, n):
    return im.resize((im.width * n, im.height * n), Image.NEAREST)


def tint(im, color, amount):
    """Blend opaque pixels toward a colour (for distance haze)."""
    color = rgba(color)
    out = im.copy()
    px = out.load()
    for y in range(out.height):
        for x in range(out.width):
            r, g, b, a = px[x, y]
            if a:
                px[x, y] = (int(r + (color[0] - r) * amount),
                            int(g + (color[1] - g) * amount),
                            int(b + (color[2] - b) * amount), a)
    return out


def recolor(im, mapping):
    """Swap exact colours (palette swap)."""
    mp = {rgba(k): rgba(v) for k, v in mapping.items()}
    out = im.copy()
    px = out.load()
    for y in range(out.height):
        for x in range(out.width):
            c = px[x, y]
            if c in mp:
                px[x, y] = mp[c]
    return out


def silhouette(im, color):
    color = rgba(color)
    out = im.copy()
    px = out.load()
    for y in range(out.height):
        for x in range(out.width):
            if px[x, y][3]:
                px[x, y] = (color[0], color[1], color[2], px[x, y][3])
    return out


