const { chromium } = require('playwright');
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
  const ctx = await browser.newContext({ viewport: { width: 844, height: 390 }, deviceScaleFactor: 3, hasTouch: true, isMobile: true });
  const page = await ctx.newPage();
  await page.goto('http://127.0.0.1:8766/index.html');
  await page.waitForFunction(() => window.__m1 && window.__m1.state() === 'title');
  await page.tap('#bStart');
  await page.waitForFunction(() => window.__m1.state() === 'play');
  await page.evaluate(() => { window.__log = []; const pad = document.getElementById('pad'); ['pointerdown','pointermove','pointerup','pointercancel','lostpointercapture','gotpointercapture'].forEach(n => pad.addEventListener(n, e => window.__log.push(n + ' id=' + e.pointerId + ' ' + Math.round(e.clientX) + ',' + Math.round(e.clientY) + ' lock=' + Input.isLocked()), true)); });
  const client = await ctx.newCDPSession(page);
  const pts = {};
  const send = async type => client.send('Input.dispatchTouchEvent', { type, touchPoints: Object.keys(pts).map(id => ({ x: pts[id][0], y: pts[id][1], id: +id })) });
  const down = async (id, x, y) => { pts[id] = [x, y]; await send('touchStart'); };
  const move = async (id, x, y) => { pts[id] = [x, y]; await send('touchMove'); };
  const up = async id => { const q = pts[id]; delete pts[id]; await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [{ x: q[0], y: q[1], id: +id }] }); };
  const G = await page.evaluate(() => window.__m1.geo().G);
  await down(1, 150, 300); await move(1, 200, 302); await sleep(200);
  await down(3, G.fire.x, G.fire.y); await sleep(200);
  await move(3, G.fire.x, G.fire.y - 30); await move(3, G.fire.x, G.fire.y - 60); await sleep(60);
  await up(3); await sleep(300);
  await page.evaluate(() => window.__log.push('--- tap fire'));
  await down(3, G.fire.x, G.fire.y); await sleep(50); await up(3); await sleep(100);
  await page.evaluate(() => window.__log.push('--- after tap, lock=' + Input.isLocked()));
  await move(1, 150, 345); await sleep(200);
  await page.evaluate(() => window.__log.push('--- after pull down, crouch=' + window.__m1.sim().p.crouch + ' touches=' + Input.touches()));
  await up(1);
  console.log((await page.evaluate(() => window.__log)).join('\n'));
  await browser.close();
})();
